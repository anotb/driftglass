#!/usr/bin/env node
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationDir = path.join(root, "migrations");
const output = path.join(root, "src", "generated-migrations.ts");
const checkOnly = process.argv.includes("--check");
const files = (await readdir(migrationDir))
  .filter((name) => /^\d+.*\.sql$/i.test(name))
  .sort((left, right) => left.localeCompare(right, "en"));

if (files.length === 0) throw new Error("No SQL migrations found");

const migrations = [];
let previousVersion = 0;
for (const name of files) {
  const match = name.match(/^(\d+)/);
  if (!match) throw new Error(`Migration lacks a numeric prefix: ${name}`);
  const version = Number(match[1]);
  if (!Number.isSafeInteger(version) || version <= previousVersion) {
    throw new Error(`Migration versions must be strictly increasing: ${name}`);
  }
  previousVersion = version;
  const sql = await readFile(path.join(migrationDir, name), "utf8");
  migrations.push({ version, name, sql });
}

const generated = `// Generated by scripts/generate-migrations.mjs. Do not edit by hand.\n` +
  `export interface DriftglassMigration { readonly version: number; readonly name: string; readonly sql: string }\n\n` +
  `export const GENERATED_MIGRATIONS: readonly DriftglassMigration[] = ${JSON.stringify(migrations, null, 2)} as const;\n`;

if (checkOnly) {
  const actual = await readFile(output, "utf8").catch(() => "");
  if (actual !== generated) throw new Error(`${path.relative(root, output)} is stale; run npm run generate:migrations`);
  console.log(`Verified ${path.relative(root, output)} from ${files.length} migration(s).`);
} else {
  await writeFile(output, generated);
  console.log(`Generated ${path.relative(root, output)} from ${files.length} migration(s).`);
}
